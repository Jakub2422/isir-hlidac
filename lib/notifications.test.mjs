import assert from 'node:assert/strict';
import {notifications} from './notifications.ts';
const config={url:'https://db.test',secret:'test'};const calls=[];
const fetcher=async(url,init)=>{calls.push({url,init});return init.method==='PATCH'?new Response(null,{status:204}):Response.json([{id:'notification',read_at:null}]);};
assert.equal((await notifications(config,undefined,fetcher)).length,1);
await notifications(config,'all',fetcher);await notifications(config,'123',fetcher);
assert.match(calls[0].url,/limit=200/);assert.equal(calls[1].init.method,'PATCH');
assert.match(calls[1].url,/read_at=is.null$/);assert.match(calls[2].url,/id=eq.123$/);
assert.ok(Date.parse(JSON.parse(calls[1].init.body).read_at));
await assert.rejects(()=>notifications(config,undefined,async()=>new Response('private',{status:403})),/unavailable \(403\)/);
console.log('Notification list, read, read-all and safe errors passed');
