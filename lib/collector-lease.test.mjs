import assert from 'node:assert/strict';
import {collectorLease,startCollectorHeartbeat} from './collector-lease.ts';
const config={url:'https://db.test',secret:'test'};
let calls=0;
const fetcher=async(url,init)=>{calls++;assert.match(url,/renew_collector_lease$/);assert.equal(JSON.parse(init.body).p_token,'owner');return Response.json(true);};
assert.equal(await collectorLease('renew','owner',config,fetcher),true);
const heartbeat=startCollectorHeartbeat('owner',config,fetcher,5);
await new Promise(resolve=>setTimeout(resolve,25));
await heartbeat.ensure();await heartbeat.stop();
const stopped=calls;await new Promise(resolve=>setTimeout(resolve,20));assert.equal(calls,stopped);assert.ok(calls>=3);
const lost=startCollectorHeartbeat('owner',config,async()=>Response.json(false),10000);
await assert.rejects(()=>lost.ensure(),/lease lost/);await lost.stop();
const failed=startCollectorHeartbeat('owner',config,async()=>{throw Error('network');},10000);
await assert.rejects(()=>failed.ensure(),/lease lost/);await failed.stop();
console.log('Heartbeat renew, token forwarding, fail-closed loss and cleanup passed');
