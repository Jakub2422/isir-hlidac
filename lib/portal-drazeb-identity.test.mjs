import assert from 'node:assert/strict';
import {portalDrazebDetailIdentity} from './portal-drazeb-identity.ts';
import {dedupEvidence,dedupConfidence} from './auction-dedup.ts';
const html='<h2>Údaje o dražbě</h2><div>Spisová značka: 139EX07876/24-193</div>';
const identity=portalDrazebDetailIdentity(html);
assert.deepEqual(identity,{authority:'139',proceeding:'139EX07876/24-193'});
assert.deepEqual(portalDrazebDetailIdentity('<div>Spisová značka: 137 EX 16516/25-MB</div>'),{authority:'137',proceeding:'137EX16516/25-MB'});
assert.equal(portalDrazebDetailIdentity('<h1>Dražba RD</h1>'),undefined);
const a={source:'Portál dražeb',title:'Dům',location:'Ostrava',date:'2026-11-10',identity};
const b={...a,source:'CEVD',identity:{...identity}};
assert.equal(dedupConfidence(dedupEvidence(a),dedupEvidence(b)),'medium','proceeding alone must not auto-merge');
console.log('Portál dražeb public detail metadata: extraction and safe review-only matching passed');
