import assert from 'node:assert/strict';
import {healthWarnings,readSourceHealth} from './source-health.ts';
const now=Date.parse('2026-10-11T14:00:00Z');
const healthy={enabled:true,last_attempt:'2026-10-11T13:00:00Z',last_success:'2026-10-11T13:00:00Z',success:true,item_count:0,last_nonempty:null,consecutive_failures:0};
assert.deepEqual(healthWarnings(healthy,now),[],'empty catalog is healthy');
assert.equal(healthWarnings({...healthy,last_nonempty:'2026-10-10T13:00:00Z'},now).length,1);
assert.equal(healthWarnings({...healthy,success:false,consecutive_failures:3},now).length,2);
assert.equal(healthWarnings({...healthy,last_attempt:null},now).length,1);
assert.deepEqual(healthWarnings({...healthy,enabled:false,last_attempt:null},now),[]);
assert.equal(healthWarnings({...healthy,last_success:'2026-10-10T13:00:00Z'},now).length,1,'attempts do not hide stale success');
await assert.rejects(()=>readSourceHealth({url:'https://test.invalid',secret:'secret'},async()=>new Response('secret body',{status:403})),/^Error: Source health unavailable \(403\)$/);
console.log('Source health: healthy empty, suspicious empty, failures, never run, disabled and safe errors passed');
